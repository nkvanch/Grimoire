// Builds src/io/sheetFonts.generated.ts from the font files in assets/fonts/sheet.
//
// The PDF character sheet is printed from an HTML string with no network, so its fonts travel inside that string as base64 @font-face
// rules, one set per look. Run this after changing a font file:  node scripts/build-sheet-fonts.mjs
//
// The fonts are the Latin subsets served by Google Fonts, all under the SIL Open Font License (assets/fonts/sheet/licenses).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'assets', 'fonts', 'sheet');

/** look -> [family, style, weight (one value or a range), file] */
export const FACES = {
  illuminated: [
    ['Cormorant Garamond', 'normal', '700', 'CormorantGaramond-700.woff2'],
    ['EB Garamond', 'normal', '400 600', 'EBGaramond-var.woff2'],
    ['EB Garamond', 'italic', '400', 'EBGaramond-italic.woff2'],
  ],
  astrolabe: [
    ['Outfit', 'normal', '400 600', 'Outfit-var.woff2'],
    ['JetBrains Mono', 'normal', '400 500', 'JetBrainsMono-var.woff2'],
  ],
  ledger: [
    ['Inter', 'normal', '400 600', 'Inter-var.woff2'],
    ['Space Grotesk', 'normal', '500 700', 'SpaceGrotesk-var.woff2'],
  ],
};

const face = ([family, style, weight, file]) =>
  `@font-face{font-family:'${family}';font-style:${style};font-weight:${weight};src:url(data:font/woff2;base64,${readFileSync(join(dir, file)).toString('base64')}) format('woff2');}`;

const lines = Object.entries(FACES).map(([look, faces]) => `  ${look}: ${JSON.stringify(faces.map(face).join(''))},`);
writeFileSync(join(root, 'src', 'io', 'sheetFonts.generated.ts'),
  `// GENERATED by scripts/build-sheet-fonts.mjs from assets/fonts/sheet. Do not edit by hand.\n` +
  `// Fonts under the SIL Open Font License 1.1: see assets/fonts/sheet/licenses.\n` +
  `export const SHEET_FONT_CSS: Record<'illuminated' | 'astrolabe' | 'ledger', string> = {\n${lines.join('\n')}\n};\n`);
console.log('written src/io/sheetFonts.generated.ts');
